"""Export service: formats single answers or entire conversations as Plain Text (.txt), Markdown (.md), or PDF (.pdf)."""
import os
from datetime import datetime


def format_answer_txt(answer_data, question=""):
    title = answer_data.get("title") or "Manual Instructions"
    summary = answer_data.get("summary") or ""
    warning = answer_data.get("warning") or ""
    steps = answer_data.get("steps") or []
    
    lines = []
    lines.append("=" * 70)
    lines.append(f"AI USER MANUAL - {title.upper()}")
    lines.append("=" * 70)
    if question:
        lines.append(f"Question: {question}\n")
    if summary:
        lines.append(f"Summary:\n{summary}\n")
    if warning:
        lines.append(f"[!] WARNING: {warning}\n")
    if steps:
        lines.append("STEPS & INSTRUCTIONS:")
        lines.append("-" * 40)
        for s in steps:
            num = s.get("number", "")
            txt = s.get("text", "")
            pg = s.get("page", "")
            pg_str = f" (Manual Page {pg})" if pg else ""
            lines.append(f"Step {num}: {txt}{pg_str}")
        lines.append("")
    return "\n".join(lines)


