def format_conversation_txt(messages, title="Conversation History", manual_name=""):
    lines = ["=" * 70]
    lines.append(f"AI USER MANUAL CHAT - {title.upper()}")
    if manual_name:
        lines.append(f"Manual: {manual_name}")
    lines.append(f"Date: {datetime.now().strftime('%Y-%m-%d %H:%M')}")
    lines.append("=" * 70 + "\n")
    
    for m in messages:
        role = m.get("role", "user").upper()
        content = m.get("content", "")
        time_str = m.get("created_at", "")
        lines.append(f"[{role}] {f'({time_str})' if time_str else ''}")
        lines.append("-" * 30)
        lines.append(content.strip())
        
        data = m.get("data")
        if data and isinstance(data, dict):
            steps = data.get("steps") or []
            if steps:
                lines.append("\nDetailed Steps:")
                for s in steps:
                    num = s.get("number", "")
                    stext = s.get("text", "")
                    pg = s.get("page", "")
                    lines.append(f"  {num}. {stext} {f'(Page {pg})' if pg else ''}")
        lines.append("\n" + "=" * 50 + "\n")
    return "\n".join(lines)


def format_conversation_md(messages, title="Conversation History", manual_name=""):
    lines = [f"# {title}\n"]
    if manual_name:
        lines.append(f"**Manual:** {manual_name}  ")
    lines.append(f"**Exported:** {datetime.now().strftime('%Y-%m-%d %H:%M')}\n")
    lines.append("---\n")
    
    for m in messages:
        role = m.get("role", "user")
        content = m.get("content", "")
        if role == "user":
            lines.append(f"### 👤 User\n\n> {content}\n")
        else:
            lines.append("### 🤖 Assistant\n")
            data = m.get("data")
            if data and isinstance(data, dict):
                atitle = data.get("title")
                summary = data.get("summary")
                warning = data.get("warning")
                steps = data.get("steps") or []
                if atitle:
                    lines.append(f"**{atitle}**\n")
                if summary:
                    lines.append(f"{summary}\n")
                if warning:
                    lines.append(f"> ⚠️ **Warning:** {warning}\n")
                if steps:
                    for s in steps:
                        num = s.get("number", "")
                        stxt = s.get("text", "")
                        pg = s.get("page", "")
                        lines.append(f"{num}. {stxt} {f'*(Page {pg})*' if pg else ''}")
                    lines.append("")
            else:
                lines.append(f"{content}\n")
            lines.append("---\n")
    return "\n".join(lines)


