def _get_svg_content(name: str, color: str = "#00FF85") -> str:
    path_data = LUCIDE_PATHS.get(name, LUCIDE_PATHS["zap"])
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" '
        f'fill="none" stroke="{color}" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">'
        f'{path_data}</svg>'
    )


def get_pixmap(name: str, color: str = "#00FF85", size: int = 20) -> QPixmap:
    """Render a Lucide icon as a high-DPI QPixmap with the given stroke color and pixel size."""
    svg_xml = _get_svg_content(name, color)
    renderer = QSvgRenderer(QByteArray(svg_xml.encode("utf-8")))
    pix = QPixmap(size, size)
    pix.fill(Qt.GlobalColor.transparent)
    painter = QPainter(pix)
    renderer.render(painter)
    painter.end()
    return pix


def get_icon(name: str, color: str = "#00FF85", size: int = 20) -> QIcon:
    """Return a QIcon for buttons and actions."""
    return QIcon(get_pixmap(name, color, size))
